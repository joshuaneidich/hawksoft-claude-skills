#!/usr/bin/env node
// Build the three "enforcement" variants of the HawkSoft plugin.
//
// The customer decides how assertively the skill activates by choosing which
// generated folder to install. This script copies the plugin into dist/ three
// times, tunes each copy's SKILL.md description, and (for the strict variant)
// adds a UserPromptSubmit hook that guarantees routing. It then prints which
// folder to use for which behavior.
//
// Usage:
//   npm run build            # writes to dist/, prints the three paths
//
// dist/ is build output and is gitignored — regenerate it any time.

import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, '..');
const distRoot = join(repoRoot, 'dist');
const skillRel = 'skills/hawksoft-operations/SKILL.md';

// Shared description for the two auto-activating variants: front-loads "HawkSoft"
// and widens the trigger surface so the assistant reaches for the skill readily.
const AUTO_DESCRIPTION =
  'HawkSoft agency-management workflows. Use whenever HawkSoft is mentioned, or ' +
  'the user asks how to complete — or asks the assistant to perform — any HawkSoft ' +
  'operation such as logging phone calls or documenting client conversations. ' +
  'Currently covers logging inbound customer phone calls.';

const MANUAL_DESCRIPTION =
  'HawkSoft agency-management workflows (manual mode). Use only when the user ' +
  'explicitly invokes /hawksoft:hawksoft-operations or asks by name for a documented ' +
  'HawkSoft procedure. Do not auto-activate on incidental mentions of HawkSoft.';

const variants = [
  {
    id: 'hawksoft-always-enforce',
    label: 'Always enforce (strict)',
    blurb:
      'A bundled hook reminds the assistant to route through the skill every time ' +
      'HawkSoft is mentioned. Deterministic — closest to "always."',
    description: AUTO_DESCRIPTION,
    hook: true
  },
  {
    id: 'hawksoft-soft-trigger',
    label: 'Soft trigger (recommended default)',
    blurb:
      'A strong description auto-activates the skill on HawkSoft requests, but the ' +
      'assistant still decides. No hook, no extra setup.',
    description: AUTO_DESCRIPTION,
    hook: false
  },
  {
    id: 'hawksoft-manual',
    label: 'Manual only',
    blurb:
      'The skill activates only when the user explicitly runs ' +
      '/hawksoft:hawksoft-operations. No auto-trigger, no hook.',
    description: MANUAL_DESCRIPTION,
    hook: false
  }
];

function setDescription(skillMdPath, description) {
  const content = readFileSync(skillMdPath, 'utf8');
  if (!/^description:.*$/m.test(content)) {
    throw new Error(`No description frontmatter found in ${skillMdPath}`);
  }
  writeFileSync(skillMdPath, content.replace(/^description:.*$/m, `description: ${description}`));
}

function addHook(variantDir) {
  const hooksDir = join(variantDir, 'hooks');
  const scriptsDir = join(variantDir, 'scripts');
  mkdirSync(hooksDir, { recursive: true });
  mkdirSync(scriptsDir, { recursive: true });

  cpSync(join(scriptDir, 'hawksoft-guard.mjs'), join(scriptsDir, 'hawksoft-guard.mjs'));

  const hooksJson = {
    description:
      'Remind the assistant to use the hawksoft-operations skill whenever HawkSoft is mentioned.',
    hooks: {
      UserPromptSubmit: [
        {
          hooks: [
            {
              type: 'command',
              command: 'node "${CLAUDE_PLUGIN_ROOT}/scripts/hawksoft-guard.mjs"'
            }
          ]
        }
      ]
    }
  };
  writeFileSync(join(hooksDir, 'hooks.json'), JSON.stringify(hooksJson, null, 2) + '\n');
}

function buildVariant(variant) {
  const variantDir = join(distRoot, variant.id);
  rmSync(variantDir, { recursive: true, force: true });
  mkdirSync(variantDir, { recursive: true });

  // Copy the plugin surface: manifests and the skill content.
  cpSync(join(repoRoot, '.claude-plugin'), join(variantDir, '.claude-plugin'), {
    recursive: true
  });
  cpSync(join(repoRoot, 'skills'), join(variantDir, 'skills'), { recursive: true });

  setDescription(join(variantDir, skillRel), variant.description);

  if (variant.hook) addHook(variantDir);

  return variantDir;
}

function writeIndex(builtPaths) {
  const rows = variants
    .map((v, i) => {
      const rel = `dist/${v.id}`;
      return (
        `## ${v.label}\n\n` +
        `${v.blurb}\n\n` +
        `Install this folder:\n\n` +
        '```text\n' +
        `claude --plugin-dir ${rel}\n` +
        '```\n'
      );
    })
    .join('\n');

  const md =
    `# Choose a HawkSoft variant\n\n` +
    `This folder is generated by \`npm run build\`. Each subfolder is a complete, ` +
    `installable copy of the HawkSoft plugin tuned to a different activation behavior. ` +
    `Pick the one that matches how assertively you want the skill to engage, then install ` +
    `only that folder.\n\n` +
    rows +
    `\nAll three expose the same command, \`/hawksoft:hawksoft-operations\`, and the same ` +
    `documented procedures. They differ only in how eagerly the skill activates. Install ` +
    `just one at a time.\n`;

  writeFileSync(join(distRoot, 'README.md'), md);
}

// -------- run --------
mkdirSync(distRoot, { recursive: true });
const built = variants.map((v) => ({ v, path: buildVariant(v) }));
writeIndex(built.map((b) => b.path));

console.log('\nBuilt 3 HawkSoft variants into dist/:\n');
for (const { v } of built) {
  console.log(`  dist/${v.id}`);
  console.log(`    ${v.label} — ${v.blurb.replace(/\s+/g, ' ')}`);
  console.log(`    install:  claude --plugin-dir dist/${v.id}\n`);
}
console.log('See dist/README.md for the full comparison. Install exactly one folder.\n');
